// runSigner runs a signer for keyID on the stand-in's engine, its config in
// a temporary file, its intervals short; it stops when the test ends.
func runSigner(t *testing.T, cp *signintest.Server, keyID string, seed []byte) *signer.Signer {
	t.Helper()
	secret, err := agentkey.NewSecret(signintest.Environment, keyID, seed)
	if err != nil {
		t.Fatal(err)
	}
	cfg := &signer.Config{Engine: cp.URL + "/a/" + signintest.AccountID + "/v1", KeyID: keyID, Secret: secret, VenueKeys: map[string]signer.VenueKey{}}
	path := filepath.Join(t.TempDir(), "agent.json")
	if err := cfg.Save(path); err != nil {
		t.Fatal(err)
	}
	s, err := signer.New(cfg, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	s.ConfigPath = path
	s.PollWait, s.KeySyncInterval, s.PermissionInterval = time.Second, 20*time.Millisecond, 50*time.Millisecond
	ctx, cancel := context.WithCancel(context.Background())
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		_ = s.Run(ctx)
	}()
	t.Cleanup(func() { cancel(); wg.Wait() })
	return s
}

func eventually(t *testing.T, what string, ok func() bool) {
	t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for !ok() {
		if time.Now().After(deadline) {
			t.Fatalf("never: %s", what)
		}
		time.Sleep(20 * time.Millisecond)
	}
}

func seed(b byte) []byte {
	s := make([]byte, 32)
	for i := range s {
		s[i] = b + byte(i)
	}
	return s
}

func pub(s []byte) string { return base64.StdEncoding.EncodeToString(agentkey.FromSeed(s).PublicKey()) }

// One agent, two trade keys syncing at once: a bot's (issued) and a trading
// machine's (registered). A trading key set aside for the machine names it
// from creation (VenueKeyCreate.agentKeyId): the bot's signer, running
// first, runs no key generation for it, and the machine's makes it. A
// trading key that names no one is the first signer's; generated by the
// bot's issued key it still names no one.
func TestOnlyTheNamedHolderGeneratesATradingKey(t *testing.T) {
	cp := signintest.New()
	defer cp.Close()
	agent := cp.Engine.AddAgent("Mixed", api.AgentPermissionTrade)
	bot := cp.Engine.Issue(agent, pub(seed(1)), api.AgentKeyScopeTrade)
	machine := cp.Engine.Register(agent, pub(seed(2)), api.AgentKeyScopeTrade, time.Now().Add(180*24*time.Hour))
	vk := cp.Engine.AddVenueKey(agent, machine)
	if keys := cp.Engine.VenueKeys(); keys[0].AgentKeyId == nil || *keys[0].AgentKeyId != machine {
		t.Fatalf("the holder is not named from creation: %+v", keys[0])
	}

	botSigner := runSigner(t, cp, bot, seed(1))
	time.Sleep(300 * time.Millisecond) // the bot's signer syncs alone, many times
	if n := len(cp.Engine.Keygens()); n != 0 {
		t.Fatalf("the bot's signer ran %d key generation rounds for the machine's key", n)
	}
	machineSigner := runSigner(t, cp, machine, seed(2))
	eventually(t, "the machine makes its trading key", func() bool { _, ok := machineSigner.HeldVenueKeys()[vk]; return ok })
	time.Sleep(100 * time.Millisecond)
	for _, by := range cp.Engine.Keygens() {
		if by != machine {
			t.Fatalf("key generation rounds by %v, want the machine's only", cp.Engine.Keygens())
		}
	}
	if _, held := botSigner.HeldVenueKeys()[vk]; held {
		t.Fatal("the bot's signer holds the machine's trading key")
	}
	if keys := cp.Engine.VenueKeys(); *keys[0].AgentKeyId != machine || keys[0].Keygen == nil || *keys[0].Keygen != api.VenueKeyKeygenDone {
		t.Fatalf("after key generation: %+v", keys[0])
	}

	// A key that names no holder: the bot's signer makes it, and an issued
	// key's generation names no one.
	free := cp.Engine.AddVenueKey(agent, "")
	eventually(t, "a signer makes the free key", func() bool {
		_, b := botSigner.HeldVenueKeys()[free]
		_, m := machineSigner.HeldVenueKeys()[free]
		return b || m
	})
	for _, k := range cp.Engine.VenueKeys() {
		if k.Id != free {
			continue
		}
		_, byBot := botSigner.HeldVenueKeys()[free]
		switch {
		case byBot && k.AgentKeyId != nil:
			t.Fatalf("the bot's issued key was recorded as the holder: %s", *k.AgentKeyId)
		case !byBot && (k.AgentKeyId == nil || *k.AgentKeyId != machine):
			t.Fatalf("the machine generated it but is not named: %+v", k)
		}
	}
}
