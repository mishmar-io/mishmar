// DefaultKeySyncInterval is how often Run compares the trading keys this
// signer holds with the engine's list of the agent's.
const DefaultKeySyncInterval = 5 * time.Second

// maxSyncBackoff bounds how long a failing sync waits between attempts.
const maxSyncBackoff = time.Minute

// Generated is a trading key SyncKeys made: what the venue needs to know it.
type Generated struct {
	VenueKeyID         string
	ConnectedAccountID string
	Venue              string
	// Network is a Hyperliquid key's network, mainnet or testnet.
	Network string
	// Scheme is SchemeECDSA2p or SchemeFrostEd25519.
	Scheme string
	// Address is the API wallet of a two-party ECDSA key (Hyperliquid), for
	// the master account to approve.
	Address string
	// PublicKeyPEM is the public key of a FROST key (Binance), to register
	// at the exchange.
	PublicKeyPEM string
}

// fileStamp is how the config file looked when it was last read or written.
type fileStamp struct {
	mod  time.Time
	size int64
}

// SyncKeys brings the trading keys this signer holds in line with the
// engine's list of the agent's, once:
//
//  1. the config file is read again when it changed, so a key another
//     command wrote into it ("signer keygen", "signer add-key") is held
//     without a restart;
//  2. every key the engine lists for this agent that waits for key
//     generation (the console added it without a share) is generated now,
//     two rounds with the engine's signer, and its share saved before the
//     next one starts; what came out is returned for the caller to show;
//  3. the shares of keys the engine reports revoked or expired are dropped.
//
// A key the engine lists that this signer neither holds nor can generate
// (generated by another signer, or whose config file was lost) is logged
// once; the signer cannot sign with it. ConfigPath is where it saves.
func (s *Signer) SyncKeys(ctx context.Context) ([]Generated, error) {
	if s.ConfigPath == "" {
		return nil, errors.New("signer: SyncKeys needs ConfigPath, the file to save keys to")
	}
	engineKeys, err := s.Client.VenueKeys(ctx)
	if err != nil {
		return nil, err
	}
	next := s.keysWithFile()
	var made []Generated
	for _, k := range engineKeys {
		if _, held := next[k.Id]; held {
			continue
		}
		switch {
		case k.Status == api.VenueKeyStatusRevoked || k.Status == api.VenueKeyStatusExpired:
			continue
		case k.Keygen != nil && *k.Keygen == api.VenueKeyKeygenPending:
		case k.Status == api.VenueKeyStatusActive:
			s.warnOnce(k, "signer: the engine lists an active trading key this signer holds no share of; orders on it fail until the share is restored or the key is replaced in the console")
			continue
		default:
			s.warnOnce(k, "signer: the engine lists a trading key this signer holds no share of and cannot generate, since its key generation is done; replace it in the console if this is the agent's only signer")
			continue
		}
		scheme, ok := SchemeForVenue(string(k.Venue))
		if !ok {
			s.warnOnce(k, "signer: a trading key waits for key generation on a venue whose keys this signer cannot make")
			continue
		}
		network := ""
		if k.Venue == api.VenueHyperliquid {
			if network, err = s.hyperliquidNetwork(ctx, k.ConnectedAccountId); err != nil {
				return made, err
			}
		}
		s.Logger.Info("signer: generating a trading key with the engine's signer", "venueKey", k.Id, "connectedAccount", k.ConnectedAccountId, "venue", k.Venue, "scheme", scheme)
		g, err := RunKeygen(ctx, s.Client, k.Id, scheme)
		if err != nil {
			return made, fmt.Errorf("signer: key generation for %s: %w", k.Id, err)
		}
		next[k.Id] = VenueKey{ConnectedAccountID: k.ConnectedAccountId, Venue: string(k.Venue), Scheme: g.Scheme, Share: g.Share, Network: network}
		// Saved before the next key: a stop between two loses nothing.
		if err := s.saveKeys(next); err != nil {
			return made, err
		}
		s.setVenueKeys(next, nil)
		out := Generated{VenueKeyID: k.Id, ConnectedAccountID: k.ConnectedAccountId, Venue: string(k.Venue), Network: network, Scheme: g.Scheme, Address: g.Address}
		if g.Scheme == SchemeFrostEd25519 {
			out.PublicKeyPEM = frost.PublicKeyPEM(g.PublicKey)
		}
		made = append(made, out)
	}
	tmp := Config{VenueKeys: next}
	if dropped := tmp.PruneVenueKeys(engineKeys); len(dropped) > 0 {
		if err := s.saveKeys(next); err != nil {
			return made, err
		}
		s.setVenueKeys(next, dropped)
		s.Logger.Info("signer: dropped the shares of keys the engine reports expired or revoked", "venueKeys", strings.Join(dropped, ", "))
		return made, nil
	}
	s.setVenueKeys(next, nil)
	return made, nil
}

// keysWithFile is a copy of the keys in memory plus any the config file
// holds that memory does not: a key another command wrote while this signer
// runs. The file is read only when it changed since the last look.
func (s *Signer) keysWithFile() map[string]VenueKey {
	next := maps.Clone(s.venueKeys())
	if next == nil {
		next = map[string]VenueKey{}
	}
	info, err := os.Stat(s.ConfigPath)
	if err != nil {
		return next
	}
	stamp := fileStamp{info.ModTime(), info.Size()}
	s.mu.Lock()
	seen := s.fileSeen == stamp
	s.fileSeen = stamp
	s.mu.Unlock()
	if seen {
		return next
	}
	cfg, err := Load(s.ConfigPath)
	if err != nil {
		s.Logger.Warn("signer: the config file no longer loads; keeping the keys in memory", "path", s.ConfigPath, "err", err)
		return next
	}
	var adopted []string
	for id, k := range cfg.VenueKeys {
		if _, held := next[id]; !held {
			next[id] = k
			adopted = append(adopted, id)
		}
	}
	if len(adopted) > 0 {
		sort.Strings(adopted)
		s.Logger.Info("signer: holding trading keys another command added to the config", "venueKeys", strings.Join(adopted, ", "))
	}
	return next
}

// saveKeys writes the config with these keys, mode 0600, atomically.
func (s *Signer) saveKeys(next map[string]VenueKey) error {
	s.mu.Lock()
	tmp := *s.Config
	s.mu.Unlock()
	tmp.VenueKeys = next
	if err := tmp.Save(s.ConfigPath); err != nil {
		return err
	}
	if info, err := os.Stat(s.ConfigPath); err == nil {
		s.mu.Lock()
		s.fileSeen = fileStamp{info.ModTime(), info.Size()}
		s.mu.Unlock()
	}
	return nil
}

// venueKeys is the keys the signer holds now. The map is replaced as a
// whole (setVenueKeys), never changed in place, so a snapshot stays good.
func (s *Signer) venueKeys() map[string]VenueKey {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.Config.VenueKeys
}

// setVenueKeys publishes a new set of keys and forgets the parsed shares of
// the dropped ones.
func (s *Signer) setVenueKeys(next map[string]VenueKey, dropped []string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.Config.VenueKeys = next
	for _, id := range dropped {
		delete(s.shares, id)
		delete(s.ecdsaKeys, id)
	}
}

// hyperliquidNetwork is the network of a Hyperliquid connected account, which
// the key's digests depend on.
func (s *Signer) hyperliquidNetwork(ctx context.Context, connectedAccountID string) (string, error) {
	ta, err := s.Client.ConnectedAccount(ctx, connectedAccountID)
	if err != nil {
		return "", fmt.Errorf("signer: reading connected account %s for the key's network: %w", connectedAccountID, err)
	}
	hl, err := ta.Setup.AsHyperliquidSetup()
	if err != nil || hl.Network == "" {
		return "", fmt.Errorf("signer: connected account %s names no Hyperliquid network in its setup", connectedAccountID)
	}
	if _, err := hyperliquid.ParseNetwork(string(hl.Network)); err != nil {
		return "", fmt.Errorf("signer: connected account %s: %w", connectedAccountID, err)
	}
	return string(hl.Network), nil
}

// warnOnce logs the message once per key, with the key's particulars.
func (s *Signer) warnOnce(k api.VenueKey, msg string) {
	s.mu.Lock()
	if s.warned == nil {
		s.warned = map[string]bool{}
	}
	seen := s.warned[k.Id+" "+msg]
	s.warned[k.Id+" "+msg] = true
	s.mu.Unlock()
	if !seen {
		s.Logger.Warn(msg, "venueKey", k.Id, "connectedAccount", k.ConnectedAccountId, "venue", k.Venue, "status", k.Status)
	}
}

// syncLoop runs SyncKeys every KeySyncInterval until ctx ends, backing off
// while the engine cannot be reached, and logs each key it makes with what
// the venue needs next.
func (s *Signer) syncLoop(ctx context.Context) {
	interval := s.KeySyncInterval
	if interval <= 0 {
		interval = DefaultKeySyncInterval
	}
	backoff := interval
	for {
		made, err := s.SyncKeys(ctx)
		for _, g := range made {
			s.logGenerated(g)
		}
		if ctx.Err() != nil {
			return
		}
		wait := interval
		if err != nil {
			wait = backoff
			backoff = min(backoff*2, maxSyncBackoff)
			s.Logger.Warn("signer: syncing trading keys with the engine failed", "err", err, "retryIn", wait)
		} else {
			backoff = interval
		}
		select {
		case <-time.After(wait):
		case <-ctx.Done():
			return
		}
	}
}

// logGenerated says what the venue needs for a key just made.
func (s *Signer) logGenerated(g Generated) {
	if g.Scheme == SchemeECDSA2p {
		s.Logger.Info("signer: trading key made; approve its API wallet at the venue", "venueKey", g.VenueKeyID, "connectedAccount", g.ConnectedAccountID,
			"venue", g.Venue, "network", g.Network, "apiWallet", g.Address, "name", HyperliquidAgentName(s.Config.AgentID),
			"where", hyperliquidAPIPage(g.Network)+" (paste the address, give it the name), or the console")
		return
	}
	s.Logger.Info("signer: trading key made; register its public key at the venue", "venueKey", g.VenueKeyID, "connectedAccount", g.ConnectedAccountID,
		"venue", g.Venue, "publicKey", g.PublicKeyPEM,
		"then", "enter the key id the venue issues in the console (the agent's Keys tab), with this signer running")
}

// HyperliquidAgentName is the name Mishmar gives an agent's API wallet at
// Hyperliquid: "mishmar-" and the last eight characters of the agent's id,
// the same for every key the agent gets, so approving a replacement takes
// over the slot of the key it replaces.
func HyperliquidAgentName(agentID string) string {
	if len(agentID) > 8 {
		agentID = agentID[len(agentID)-8:]
	}
	return "mishmar-" + agentID
}

// hyperliquidAPIPage is where API wallets are approved on each network.
func hyperliquidAPIPage(network string) string {
	if network == string(hyperliquid.Testnet) {
		return "https://app.hyperliquid-testnet.xyz/API"
	}
	return "https://app.hyperliquid.xyz/API"
}
